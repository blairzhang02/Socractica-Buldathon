import type { Unit } from "@/lib/types";

/**
 * Mockup supplier list — one standing delivery per ingredient the recipes use,
 * with the supplier names and prices taken from the catalog. Reserved
 * `.example` addresses, so nothing here can actually be emailed.
 *
 * Daily amounts are not stored. They are worked out from what the orders got
 * through over the sample window, times `buyingFactor`, so the numbers stay
 * right however the order data grows.
 */
export type Supplier = {
  id: string;
  name: string;
  /** What this supplier delivers, in plain words. */
  item: string;
  email: string;
  icon: string;
  /** Catalog ingredient this supplier covers. Hand-added rows have none, so
   *  they get no amount and no advice. */
  ingredientId?: string;
  unit?: Unit;
  /** Price of one `unit`. */
  unitPrice?: number;
  /**
   * How much she buys against what the orders actually need. 1 is exactly
   * enough; 1.25 is a quarter more than she gets through; 0.75 is short.
   */
  buyingFactor?: number;
  /** Cost per day, typed in by hand when there is no ingredient to measure. */
  dailyCost?: number;
};

